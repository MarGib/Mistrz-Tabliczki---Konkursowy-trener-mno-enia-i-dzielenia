export function createFreshProfile(
  name: string,
  avatarId: UserProfile['avatarId'] = 'av-20',
  now = Date.now(),
  customAvatarSpec?: UserProfile['customAvatarSpec'],
  schoolName?: string,
  className?: string
): UserProfile {
  const cleanSchool = schoolName?.trim() || undefined;
  const cleanClass = className?.trim() || undefined;
  return {
    id: `user-${now}-${Math.random().toString(36).slice(2, 7)}`,
    name: name.trim() || 'Mistrz',
    schoolName: cleanSchool,
    className: cleanClass,
    avatarId,
    customAvatarSpec,
    xp: 0,
    streakDays: 0,
    lastActiveDate: '',
    unlockedStageIds: ['stage-1'],
    completedStageIds: [],
    earnedBadges: [],
    memories: {},
    sessions: [],
    tournamentBests: {},
    settings: { ...DEFAULT_SETTINGS },
    activeThemeId: DEFAULT_THEME_ID,
    customThemes: [],
  };
}
